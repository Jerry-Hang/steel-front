fn tr(x: f32, y: f32, z: f32) -> Mat4 {
    Mat4::from_translation(glam::Vec3::new(x, y, z))
}

fn rx(a: f32) -> Mat4 {
    Mat4::from_rotation_x(a)
}

fn ry90() -> Mat4 {
    Mat4::from_rotation_y(std::f32::consts::FRAC_PI_2)
}
